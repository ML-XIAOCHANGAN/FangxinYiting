// 交付包固定命名为「放心一听.apk」，落在工程根目录 release/ 下，随签名一起作为对外交付物。
val deliveryApkName = "放心一听.apk"

tasks.register<Copy>("packageDeliveryApk") {
    group = "distribution"
    description = "把 release 包重命名为 $deliveryApkName 输出到 release/"
    dependsOn("assembleRelease")
    from(layout.buildDirectory.dir("outputs/apk/release")) {
        include("*.apk")
    }
    rename(".*\\.apk", deliveryApkName)
    into(rootProject.layout.projectDirectory.dir("release"))
}
